#!/usr/bin/env bash
# Writes the M20 reports from the seeded database (run after ./run_phase1.sh m19):
#   docs/phase5-query-report.md     every fixed and module query: purpose, SQL, output, and for the
#                                   fixed (non-transactional) queries the EXPLAIN (ANALYZE, BUFFERS) plan
#   docs/phase5-seed-validation.md  the seed validation (docket Section 5 rules and data-quality findings)
set -eo pipefail
C=talentra-pg
psql_run() { docker exec -i $C psql -U postgres -d talentra -X -q -v ON_ERROR_STOP=1 -P pager=off "$@"; }
scale=$(echo "SHOW talentra.seed_scale" | psql_run -At)
size=$(echo "SELECT pg_size_pretty(pg_database_size('talentra'))" | psql_run -At)
stamp=$(date -u +"%Y-%m-%d %H:%M UTC")

section() {   # $1 = query file, $2 = 1 to add the execution plan
  local f=$1 title body
  title=$(head -1 "$f" | sed 's/^-- //')
  echo "### $title"; echo
  { sed -n '2,/^[^-]/p' "$f" | grep '^-- ' | grep -v 'explain: no' | sed 's/^-- //'; } || true; echo
  echo '```sql'; grep -v '^--' "$f"; echo '```'; echo
  echo 'Output:'; echo; echo '```text'
  { cat sql/queries/params.sql; cat "$f"; } | psql_run 2>&1 | { grep -v '^$' || true; } | head -40
  echo '```'; echo
  if [ "$2" = 1 ] && ! grep -q 'explain: no' "$f"; then
    echo 'Execution plan (`EXPLAIN (ANALYZE, BUFFERS)`):'; echo; echo '```text'
    { cat sql/queries/params.sql; printf 'EXPLAIN (ANALYZE, BUFFERS) '; grep -v '^--' "$f"; } | psql_run 2>&1
    echo '```'; echo
  fi
}

{
  echo "# Talentra — Query Report (Milestone 20)"; echo
  echo "Generated by \`run_report.sh\` on $stamp from the seeded database (seed scale $scale; database size $size)."
  echo "Scale 1 = laptop scale: 1M candidate profiles, 100k job requirements, 5M applications."
  echo "Queries live in \`sql/queries/\`; their parameters (a city, a skill, the busiest requirement, …) are resolved from the data by \`sql/queries/params.sql\`."
  echo "Transactional queries run inside a transaction that is rolled back, so the report leaves the data unchanged."; echo
  echo "## Fixed query set (B65)"; echo
  for f in sql/queries/fixed/*.sql; do section "$f" 1; done
  echo "## Module queries (B67–B69)"; echo
  for f in sql/queries/module/*.sql; do section "$f" 0; done
} > docs/phase5-query-report.md

{
  echo "# Talentra — Seed Validation Report (Milestone 20, B66)"; echo
  echo "Generated by \`run_report.sh\` on $stamp (seed scale $scale; database size $size) from \`sql/queries/validation.sql\`."; echo
  echo "- **rule**: a docket Section 5 standard or design rule checked on the data; must have 0 violations."
  echo "- **finding**: a data-quality issue the dataset carries on purpose, as migrated real data would. It must be detected; it is recorded here, and the coverage gap register lists the related follow-up."; echo
  echo '```text'; psql_run < sql/queries/validation.sql; echo '```'; echo
  echo "## Row counts (largest tables; planner statistics, so approximate)"; echo; echo '```text'
  echo "SELECT relname AS table_name, n_live_tup AS approx_rows FROM pg_stat_user_tables WHERE relname !~ '_p([0-9]{6}|default)\$' ORDER BY n_live_tup DESC LIMIT 25" | psql_run
  echo "SELECT p.relname AS partitioned_table, sum(s.n_live_tup) AS approx_rows FROM pg_inherits i JOIN pg_class p ON p.oid = i.inhparent JOIN pg_stat_user_tables s ON s.relid = i.inhrelid GROUP BY p.relname ORDER BY 2 DESC" | psql_run
  echo '```'
} > docs/phase5-seed-validation.md
echo "wrote docs/phase5-query-report.md and docs/phase5-seed-validation.md"
