"""Latency benchmark of the access patterns (NFR-PERF-01). Writes docs/benchmark-results.md.

Each bench/queries/apNN_*.sql runs inside the container through psql over the local socket, as the actor named in its
"-- as:" line (the runtime role with that user's identity, so row-level security is included in the cost), inside a
transaction that is rolled back (write patterns leave nothing behind). Parameters come from bench/params.sql.
3 warm-up runs are discarded, then --runs measured runs; latency is psql's \\timing per execution (server time plus
protocol, rows discarded). Reported: rows, min, p50, p95, p99, max in ms, and the EXPLAIN (ANALYZE, BUFFERS) plan.

usage: python bench/bench.py [--runs 50] [--db talentra_v2] [--container talentra-pg] [--out docs/benchmark-results.md]
"""
import argparse, datetime, glob, os, re, statistics, subprocess

ACTORS = {  # actor -> (role, psql variable holding the user id)
    'candidate': ('v2_app', 'cand_user'), 'recruiter': ('v2_app', 'rec_user'), 'admin': ('v2_app', 'admin_user'),
    'downloader': ('v2_app', 'dl_user'), 'worker': ('v2_worker', None), 'owner': (None, None)}

def pct(vals, p):
    s = sorted(vals); k = (len(s) - 1) * p / 100; f = int(k)
    return s[f] if f == len(s) - 1 else s[f] + (s[f + 1] - s[f]) * (k - f)

def psql(args, script):
    out = subprocess.run(['docker', 'exec', '-i', args.container, 'psql', '-U', 'postgres', '-d', args.db, '-X', '-q', '-At', '-v', 'ON_ERROR_STOP=1'],
                         input=script, capture_output=True, text=True, encoding='utf-8')
    if out.returncode != 0:
        raise SystemExit(out.stderr.strip()[:800])
    return out.stdout

def run(path, args, params):
    text = open(path, encoding='utf-8').read()
    title = text.splitlines()[0].lstrip('- ').strip()
    actor = re.search(r'^-- as: (\w+)', text, re.M).group(1)
    body = '\n'.join(l for l in text.splitlines() if not l.startswith('--')).strip()
    role, user_var = ACTORS[actor]
    prelude = 'BEGIN;\n'
    if user_var:
        prelude += f"SELECT set_config('app.user_id', :'{user_var}', true) \\g /dev/null\n"
    if role:
        prelude += f'SET LOCAL ROLE {role};\n'
    script = params + prelude + '\\o /dev/null\n' + (body + '\n') * 3 + '\\o\n\\timing on\n\\o /dev/null\n' + (body + '\n') * args.runs
    script += '\\o\n\\timing off\n\\o /dev/null\n' + body + '\n\\o\nSELECT :ROW_COUNT AS rows_returned;\n'
    script += 'SELECT \'--plan--\';\nEXPLAIN (ANALYZE, BUFFERS, COSTS OFF) ' + body + '\nROLLBACK;\n'
    out = psql(args, script)
    times = [float(t) for t in re.findall(r'^Time: ([0-9.]+) ms', out, re.M)]
    if len(times) != args.runs:
        raise SystemExit(f'{path}: expected {args.runs} timings, got {len(times)}')
    head, plan = out.split('--plan--\n', 1)
    rows = re.findall(r'^(\d+)$', head, re.M)
    return {'name': title, 'actor': actor, 'rows': rows[-1] if rows else '?', 'min': min(times), 'p50': statistics.median(times),
            'p95': pct(times, 95), 'p99': pct(times, 99), 'max': max(times), 'body': body, 'plan': plan.strip()}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs', type=int, default=50); ap.add_argument('--db', default='talentra_v2')
    ap.add_argument('--container', default='talentra-pg'); ap.add_argument('--out', default='docs/benchmark-results.md')
    args = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    params = open(os.path.join(here, 'params.sql'), encoding='utf-8').read()
    env = psql(args, "SELECT version(); SELECT pg_size_pretty(pg_database_size(current_database())); SELECT count(*) FROM candidate_profile;"
                     " SELECT count(*) FROM application; SELECT current_setting('shared_buffers') || ' / ' || current_setting('work_mem');").splitlines()
    results = []
    for f in sorted(glob.glob(os.path.join(here, 'queries', 'ap*.sql'))):
        r = run(f, args, params); results.append(r)
        print(f"{r['name'][:70]:70} p50 {r['p50']:7.2f} ms  p95 {r['p95']:7.2f} ms", flush=True)
    with open(args.out, 'w', encoding='utf-8', newline='\n') as o:
        o.write('# Benchmark results (generated)\n\n')
        o.write(f'Generated by `./run.sh bench` on {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M} UTC. Method: `bench/bench.py` docstring; '
                f'targets and analysis: [06-physical-model.md](06-physical-model.md#7-performance).\n\n')
        o.write(f'- Engine: {env[0].split(" on ")[0]}; shared_buffers / work_mem: {env[4]}\n- Data: {int(env[2]):,} candidate profiles, '
                f'{int(env[3]):,} applications, database {env[1]}\n- Runs: 3 warm-up + {args.runs} measured per pattern, warm cache, as the named actor through row-level security\n\n')
        o.write('| Access pattern | Actor | Rows | min | p50 | p95 | p99 | max |\n|---|---|---|---|---|---|---|---|\n')
        for r in results:
            o.write(f"| {r['name']} | {r['actor']} | {r['rows']} | {r['min']:.2f} | {r['p50']:.2f} | {r['p95']:.2f} | {r['p99']:.2f} | {r['max']:.2f} |\n")
        o.write('\nTimes in milliseconds.\n\n## Plans\n')
        for r in results:
            o.write(f"\n<details><summary>{r['name']}</summary>\n\n```sql\n{r['body']}\n```\n\n```text\n{r['plan']}\n```\n</details>\n")
    print('wrote', args.out)

if __name__ == '__main__':
    main()
