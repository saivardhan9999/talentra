"""Builds schema-trees.md from output-schemas.md: each output schema drawn as a tree (L1 section -> L2 parameter ->
L3 allowed values -> L4 atomic type), as a Mermaid mindmap and as a plain-text tree, with the size of each level.
The tables in output-schemas.md stay the source of truth; rerun after changing them:  python stage1/schema_trees.py"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
# optional: python stage1/schema_trees.py <schemas.md> <trees.md> "<title>"  (Phase 2 reuses this script)
src_path, out_path, heading = (sys.argv[1:4] + [None] * 3)[:3]
src_path = src_path or os.path.join(here, 'output-schemas.md')
src = open(src_path, encoding='utf-8').read()

def clean(t):
    t = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', t)          # markdown links -> text
    t = re.sub(r'\(\s*\)', '', t.replace('**', '').replace('`', ''))
    return re.sub(r'\s+', ' ', t).strip()

def mm(t):                                                    # text safe for a mindmap node
    return re.sub(r'[()\[\]{}"<>]', ' ', t).replace('  ', ' ').strip()

schemas = []                                                  # (title, [(level, param, type, [values])])
for block in re.split(r'^## ', src, flags=re.M)[1:]:
    title = block.splitlines()[0].strip()
    rows = []
    for line in block.splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) == 9 and re.fullmatch(r'\d+(\.\d+)*', cells[0]):
            values = [clean(v) for v in cells[6].split('·') if clean(v)]
            rows.append((cells[0].count('.') + 1, clean(cells[1]), clean(cells[4]), values))
    schemas.append((title, rows))

out = [heading or '# Stage 1 — Output schemas as trees (generated)', '',
       f'Each output schema from [{os.path.basename(src_path)}]({os.path.basename(src_path)}) drawn as the playbook asks: **L1 sections → L2 parameters → '
       f'L3 allowed values → L4 atomic type**. Generated by `python stage1/schema_trees.py`; the tables in {os.path.basename(src_path)} hold '
       'the full definition, reason, mandatory flag and source of every node.', '',
       '**Depth rule applied:** stop when each leaf is atomic (one meaning, one type, one rule set). Level 3 appears only where a '
       'parameter has a closed list of values; level 4 is the atomic type of each parameter. No schema needed level 5.', '']
summary = ['| Schema | L1 sections | L2 parameters | L3 allowed values | L4 typed leaves |', '|---|---|---|---|---|']
for title, rows in schemas:
    l1 = [r for r in rows if r[0] == 1]
    l2 = [r for r in rows if r[0] == 2]
    l3 = sum(len(r[3]) for r in rows)
    l4 = sum(1 for r in l2 if r[2] and r[2] != 'section')
    summary.append(f'| {title} | {len(l1)} | {len(l2)} | {l3} | {l4} |')
    root = title.split('—', 1)[-1].strip()
    mind = ['```mermaid', 'mindmap', f'  root(({mm(root)}))']
    text = ['```text', root]
    for i, (lvl, name, typ, values) in enumerate(rows):
        last1 = all(r[0] != 1 for r in rows[i + 1:]) if lvl == 1 else False
        if lvl == 1:
            mind.append(f'    {mm(name)}')
            text.append(('└── ' if last1 else '├── ') + name)
            prefix = '    ' if last1 else '│   '
            if values:                                        # values directly on a section
                mind.append('      ' + mm(' · '.join(values)))
                text.append(prefix + '└── ' + ' · '.join(values))
        else:
            nxt = rows[i + 1][0] if i + 1 < len(rows) else 1
            branch = '└── ' if nxt == 1 else '├── '
            leaf = ' · '.join(values) if values else ''
            mind.append(f'      {mm(name)}')
            if values:
                mind.append(f'        {mm(leaf)}')
            if typ and typ != 'section':               # regex patterns are unreadable in a drawing: keep them for the text tree
                mind.append('        ' + (typ.split()[0] + ' pattern' if re.search(r'[\[{]', typ) else mm(typ)))
            detail = '  [' + typ + ']' if typ and typ != 'section' else ''
            text.append(prefix + branch + name + detail + (('  ── ' + leaf) if leaf else ''))
    mind.append('```'); text.append('```')
    out += [f'## {title}', '', f'{len(l1)} sections · {len(l2)} parameters · {l3} allowed values · {l4} typed leaves', '']
    out += mind + [''] + text + ['']
out[8:8] = ['## Schema size by level', ''] + summary + ['']
with open(out_path or os.path.join(here, 'schema-trees.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('\n'.join(summary))
