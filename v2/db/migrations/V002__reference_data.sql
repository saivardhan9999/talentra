-- V002 Reference data: languages and UI translations, geography, currencies, skills, and every enumeration.
-- Requirements: FR-REF-01..04, NFR-I18N-01..03, docket rule groups 3 (enumeration, coordinates) and 7 (multilingual).
-- Reference tables are versioned with the schema (they change by migration, reviewed in git), so they carry no
-- created_by / updated_by columns: deviation D-01 in docs/06-physical-model.md.

CREATE TABLE language (
    id              smallint PRIMARY KEY,
    code            text NOT NULL CONSTRAINT uq_language_code UNIQUE CHECK (code ~ '^[a-z]{2}$'),   -- ISO 639-1
    native_name     short_text NOT NULL,
    is_ui_language  boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT true,
    sort_order      smallint NOT NULL DEFAULT 0
);

CREATE TABLE ui_label (
    id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    label_key   text NOT NULL CONSTRAINT uq_ui_label_label_key UNIQUE CHECK (label_key ~ '^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$')
);

CREATE TABLE ui_translation (
    id           integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ui_label_id  integer NOT NULL REFERENCES ui_label (id) ON DELETE CASCADE,
    language_id  smallint NOT NULL REFERENCES language (id) ON DELETE RESTRICT,
    label_text   short_text NOT NULL,
    CONSTRAINT uq_ui_translation_ui_label_id_language_id UNIQUE (ui_label_id, language_id)
);
CREATE INDEX idx_ui_translation_language_id ON ui_translation (language_id);

-- Display text with fallback to English (language 1) when the requested language has no translation (NFR-I18N-02).
CREATE FUNCTION ui_text(p_ui_label_id integer, p_language_id smallint) RETURNS text LANGUAGE sql STABLE AS $$
    SELECT t.label_text FROM ui_translation t
    WHERE t.ui_label_id = p_ui_label_id AND t.language_id IN (p_language_id, 1)
    ORDER BY (t.language_id = p_language_id) DESC LIMIT 1
$$;

CREATE TABLE currency (
    id           smallint PRIMARY KEY,
    code         char(3) NOT NULL CONSTRAINT uq_currency_code UNIQUE CHECK (code ~ '^[A-Z]{3}$'),     -- ISO 4217
    minor_units  smallint NOT NULL CHECK (minor_units BETWEEN 0 AND 3),
    is_active    boolean NOT NULL DEFAULT true
);

CREATE TABLE country (
    id                  smallint PRIMARY KEY,
    iso2                char(2) NOT NULL CONSTRAINT uq_country_iso2 UNIQUE CHECK (iso2 ~ '^[A-Z]{2}$'),
    name                short_text NOT NULL,
    phone_country_code  text NOT NULL CHECK (phone_country_code ~ '^\+[1-9][0-9]{0,3}$'),
    currency_id         smallint NOT NULL REFERENCES currency (id) ON DELETE RESTRICT,
    is_active           boolean NOT NULL DEFAULT true
);
CREATE INDEX idx_country_currency_id ON country (currency_id);

CREATE TABLE state (
    id          smallint PRIMARY KEY,
    country_id  smallint NOT NULL REFERENCES country (id) ON DELETE RESTRICT,
    code        text NOT NULL CHECK (code ~ '^[A-Z0-9]{1,5}$'),
    name        short_text NOT NULL,
    CONSTRAINT uq_state_country_id_code UNIQUE (country_id, code)
);

-- Coordinates: WGS 84, 6 decimal places (about 0.1 m), source: public geocoder, refreshed by migration (rule group 3).
CREATE TABLE city (
    id         integer PRIMARY KEY,
    state_id   smallint NOT NULL REFERENCES state (id) ON DELETE RESTRICT,
    name       short_text NOT NULL,
    latitude   latitude NOT NULL,
    longitude  longitude NOT NULL,
    is_active  boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_city_state_id_name UNIQUE (state_id, name)
);

CREATE TABLE skill (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       short_text NOT NULL,
    is_active  boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX uq_skill_name ON skill (lower(name));
CREATE INDEX idx_skill_name_trgm ON skill USING gin (lower(name) gin_trgm_ops);   -- AP-09 type-ahead

-- Every fixed set of values is a lookup table of one shape: code, UI label (translated), active flag, sort order.
CREATE PROCEDURE create_lookup(p_table text) LANGUAGE plpgsql AS $$
BEGIN
  EXECUTE format('CREATE TABLE %I (
      id           smallint PRIMARY KEY,
      code         lookup_code NOT NULL CONSTRAINT %I UNIQUE,
      ui_label_id  integer NOT NULL REFERENCES ui_label (id) ON DELETE RESTRICT,
      is_active    boolean NOT NULL DEFAULT true,
      sort_order   smallint NOT NULL DEFAULT 0)', p_table, 'uq_' || p_table || '_code');
  EXECUTE format('CREATE INDEX %I ON %I (ui_label_id)', 'idx_' || p_table || '_ui_label_id', p_table);
END $$;

-- Adds values in order (id = position), each with a UI label "<table>.<code>" and an English translation.
CREATE PROCEDURE add_lookup_values(p_table text, p_codes text[]) LANGUAGE plpgsql AS $$
DECLARE i int; l int;
BEGIN
  FOR i IN 1 .. cardinality(p_codes) LOOP
    INSERT INTO ui_label (label_key) VALUES (p_table || '.' || p_codes[i]) RETURNING id INTO l;
    INSERT INTO ui_translation (ui_label_id, language_id, label_text) VALUES (l, 1, initcap(replace(p_codes[i], '_', ' ')));
    EXECUTE format('INSERT INTO %I (id, code, ui_label_id, sort_order) VALUES ($1, $2, $3, $1)', p_table) USING i, p_codes[i], l;
  END LOOP;
END $$;

