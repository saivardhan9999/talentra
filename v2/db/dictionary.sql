-- Generates docs/data-dictionary.md from the live catalog (./run.sh dictionary). The catalog is the source of truth, so the
-- dictionary cannot drift from the schema. Class and nullability reasons come from the column comments; a column with no
-- stated class is Internal. Audit columns (created_at/by, updated_at/by) and deleted_at are described once at the top.
WITH t AS (
  SELECT c.oid, c.relname, obj_description(c.oid, 'pg_class') AS remark,
         EXISTS (SELECT 1 FROM pg_attribute a WHERE a.attrelid = c.oid AND a.attname = 'ui_label_id')
           AND EXISTS (SELECT 1 FROM pg_attribute a WHERE a.attrelid = c.oid AND a.attname = 'code') AS is_lookup
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition AND c.relname <> 'schema_migration'),
col AS (
  SELECT t.relname, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod) AS type_name, NOT a.attnotnull AS nullable,
         coalesce(substring(col_description(t.oid, a.attnum) FROM '^(Public|Internal|Personal|Sensitive)\.'), 'Internal') AS class,
         coalesce(regexp_replace(col_description(t.oid, a.attnum), '^(Public|Internal|Personal|Sensitive)\.\s*', ''), '') AS remark,
         (SELECT string_agg(CASE k.contype WHEN 'p' THEN 'PK' WHEN 'u' THEN 'UQ' WHEN 'f' THEN 'FK → ' || k.confrelid::regclass END, ', ')
          FROM pg_constraint k WHERE k.conrelid = t.oid AND a.attnum = ANY (k.conkey) AND k.contype IN ('p', 'u', 'f')) AS keys
  FROM t JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
  WHERE NOT t.is_lookup AND a.attname NOT IN ('created_at', 'created_by', 'updated_at', 'updated_by', 'deleted_at'))
SELECT '# Data dictionary (generated)' || E'\n\n'
    || 'Generated by `./run.sh dictionary` from the live catalog of `talentra_v2`; do not edit by hand. '
    || 'Class follows docket rule group 6 (Public, Internal, Personal, Sensitive; unstated = Internal). '
    || 'Every nullable column states why it may be NULL (rule group 5, enforced by test t01).' || E'\n\n'
    || '**Columns on every business table** (not repeated below): `created_at` timestamptz NOT NULL, `created_by` bigint FK → app_user '
    || '(NULL = a system process), `updated_at` timestamptz NOT NULL, `updated_by` bigint FK → app_user (NULL = system), all set by the '
    || '`set_audit_columns` trigger. **Soft-deleted tables** also have `deleted_at` timestamptz (NULL = live row; default queries and '
    || 'row-level security exclude deleted rows).' || E'\n\n'
    || '**Lookup tables** (one shape: `id` smallint PK, `code` unique, `ui_label_id` FK → ui_label, `is_active`, `sort_order`): '
    || (SELECT string_agg('`' || relname || '`', ', ' ORDER BY relname) FROM t WHERE is_lookup) || '.' || E'\n\n'
    || (SELECT string_agg(
          '## ' || t.relname || E'\n\n' || coalesce(t.remark || E'\n\n', '')
          || E'| Column | Type | Null | Keys | Class | Notes |\n|---|---|---|---|---|---|\n'
          || (SELECT string_agg(format('| %s | %s | %s | %s | %s | %s |', c.attname, c.type_name, CASE WHEN c.nullable THEN 'yes' ELSE '' END,
                                       coalesce(c.keys, ''), c.class, replace(c.remark, '|', '\|')), E'\n' ORDER BY c.attnum)
              FROM col c WHERE c.relname = t.relname),
          E'\n\n' ORDER BY t.relname)
        FROM t WHERE NOT t.is_lookup);
