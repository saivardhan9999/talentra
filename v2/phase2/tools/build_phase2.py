def example_of(tb, c):
    if c['name'] in N.COLS.get(tb, {}):
        return N.COLS[tb][c['name']][2]
    if is_lookup(tb):
        return {'id': '2', 'code': tables[tb]['codes'][min(1, len(tables[tb]['codes']) - 1)], 'ui_label_id': '57', 'is_active': 'true', 'sort_order': '2'}[c['name']]
    if c['name'] == 'id':
        return example_id(tb)
    if c['ref']:
        p = c['ref'][0]
        if is_lookup(p):
            i = int(c['default']) if (c['default'] or '').isdigit() else 1
            return f"{i} ({tables[p]['codes'][i - 1]})"
        return REF_EXAMPLES.get(p) or example_id(p)
    if c['type'] == 'boolean':
        return c['default'] or 'true'
    if c['name'] == 'sort_order':
        return '1'
    if c['name'].endswith('_id') and c['name'][:-3] in tables:     # part of a composite key only
        return example_id(c['name'][:-3])
    if c['type'] == 'timestamptz':
        return '2026-10-12 09:30:15+00'
    if c['type'] == 'date':
        return '2026-11-01'
    return ''

def business_name(tb, c):
    if c['name'] in N.COLS.get(tb, {}) and N.COLS[tb][c['name']][0]:
        return N.COLS[tb][c['name']][0]
    if (tb, c['name']) in N.FK_NAMES:
        return N.FK_NAMES[(tb, c['name'])][0]
    if c['name'] == 'id':
        return f'{ent_name(tb)} id'
    if c['ref'] and not is_lookup(c['ref'][0]) and c['name'] == c['ref'][0] + '_id':
        return ent_name(c['ref'][0])
    return human(c['name'])

def definition(tb, c):
    if c['name'] in N.COLS.get(tb, {}):
        return N.COLS[tb][c['name']][1]
    if (tb, c['name']) in N.FK_NAMES:
        return N.FK_NAMES[(tb, c['name'])][1]
    if is_lookup(tb):
        return {'id': 'Fixed id of the value (its position in the list).', 'code': 'Stable code used by programs; never shown to users.',
                'ui_label_id': 'Label of the value; text per language in ui_translation.', 'is_active': 'Whether the value can still be chosen.',
                'sort_order': 'Display order in lists.'}[c['name']]
    if c['name'] == 'id':
        return f'Surrogate key of the {ent_name(tb).lower()}; never reused.'
    if c['ref'] and is_lookup(c['ref'][0]):
        codes = tables[c['ref'][0]]['codes']
        return f"{human(c['ref'][0])}: one of {' · '.join(codes)}." + (f' {clean_definition(c)}' if clean_definition(c) else '')
    d = clean_definition(c)
    if d:
        return d
    if c['name'] == 'is_active':
        return 'Whether the row can still be chosen; inactive rows stay valid where already used.'
    if c['name'] == 'sort_order':
        return 'Display order in lists.'
    if c['name'] == 'deleted_at':
        return 'Soft-delete time; deleted rows are hidden from default queries and row-level security.'
    if c['ref']:
        return f"The {ent_name(c['ref'][0]).lower()} this {ent_name(tb).lower()} refers to."
    return ''

def proposed_class(tb, c):
    if (tb, c['name']) in N.SENSITIVE or c['class'] == 'Sensitive':
        return 'Sensitive'
    if tb in N.PERSON_TABLES and c['name'] not in N.OWNER_KEYS and c['name'] != 'deleted_at':
        return 'Personal'
