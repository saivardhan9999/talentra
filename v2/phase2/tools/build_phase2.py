def nullable_reason(c):
    if c['name'] == 'deleted_at':
        return 'the row is live'
    m = re.search(r'NULL: (.*?)(?:$|(?<=\.)\s)', c['remark'])
    return m.group(1).rstrip('.') if m else ''

def clean_definition(c):
    return re.split(r'\s*NULL:', c['remark'])[0].strip()

