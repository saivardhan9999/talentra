def col_constraints(tb, c):
    out = []
    if c['pk']:
        out.append('PK')
    if c['identity']:
        out.append('identity')
    for u in c['unique']:
        out.append('UQ' + (f' {u}' if u != '(inline)' else ''))
    if c.get('composite'):
        out.append(f"FK → {c['ref'][0]} via composite {c['composite']} ({c['ref'][1].lower()})")
    elif c['ref']:
        out.append(f"FK → {c['ref'][0]} ({c['ref'][1].lower()})")
    for name, expr in c['checks']:
        out.append(f"CK {name}" if name else f'CK `{expr.strip()}`'[:90])
    if c['type'] in DOMAINS and DOMAINS[c['type']][1]:
        out.append(f"domain {c['type']}")
    if c['default'] and not c['identity']:
        out.append(f"default {c['default']}")
    if c['generated']:
        out.append('generated')
    return ', '.join(out)

def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')

def write(name, lines):
    with open(os.path.join(PHASE2, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

