def length_of(c):
    typ = c['type']
    if typ in DOMAINS:
        base, chk = DOMAINS[typ]
        m = re.search(r'BETWEEN 1 AND (\d+)', chk or '') or re.search(r'<= (\d+)', chk or '')
        return {'person_name': '1–150 chars', 'short_text': '1–200 chars', 'medium_text': '1–2,000 chars', 'long_text': '1–20,000 chars',
                'email_address': '≤ 254 chars', 'phone_e164': '8–16 chars (+ and up to 15 digits)', 'money_amount': '14 digits, 2 decimals',
                'credit_count': '32-bit integer', 'percentage': '5 digits, 2 decimals', 'latitude': '8 digits, 6 decimals',
                'longitude': '9 digits, 6 decimals', 'lookup_code': '1–50 chars', 'sha256_digest': '32 bytes'}.get(typ, m and f'≤ {m.group(1)}' or base)
    chk = ' '.join(x[1] for x in c['checks'])
    if typ in ('text', 'jsonb'):
        m = (re.search(r'char_length\(\w+\) (?:<= (\d+)|BETWEEN \d+ AND (\d+))', chk) or re.search(r'\{\d+,(\d+)\}', chk)
             or re.search(r'pg_column_size\(\w+\) <= (\d+)', chk))
        if m:
            n = next(g for g in m.groups() if g)
            return f'≤ {n} bytes' if typ == 'jsonb' else f'≤ {n} chars'
        return 'bounded by its pattern' if chk else 'unbounded (justify)'
    m = re.match(r'char\((\d+)\)', typ)
    if m:
        return f'{m.group(1)} chars'
    return {'bigint': '64-bit', 'integer': '32-bit', 'smallint': '16-bit', 'boolean': '', 'date': '', 'timestamptz': 'µs, UTC',
            'inet': 'IPv4/IPv6', 'tsvector': ''}.get(typ, '')

