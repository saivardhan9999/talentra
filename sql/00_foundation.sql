CREATE EXTENSION IF NOT EXISTS pg_trgm;      -- trigram search on names/titles
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- exclusion constraints (Phase 2/3 windows)

SET client_encoding = 'UTF8';

-- -----------------------------------------------------------------------------
-- Actor context. The access layer runs `SET LOCAL app.current_user_id = '<id>'`
-- at the start of every transaction. created_by/updated_by default from it, so
-- a write without an identified actor fails the NOT NULL constraint.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_current_user_id() RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT nullif(current_setting('app.current_user_id', true), '')::bigint
$$;

-- Maintains updated_at/updated_by and freezes created_at/created_by.
CREATE OR REPLACE FUNCTION trg_set_audit_columns() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.created_at := OLD.created_at;
    NEW.created_by := OLD.created_by;
    NEW.updated_at := now();
    NEW.updated_by := app_current_user_id();
    IF NEW.updated_by IS NULL THEN
        RAISE EXCEPTION 'app.current_user_id is not set; anonymous updates are not allowed';
    END IF;
    RETURN NEW;
END $$;

-- Append-only guard for ledgers, history and event tables (rule groups 4 and 10).
CREATE OR REPLACE FUNCTION trg_forbid_modification() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'table % is append-only: % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'insufficient_privilege';
END $$;

-- Attach trg_set_audit_columns to every table that has updated_at and no trigger yet.
CREATE OR REPLACE PROCEDURE attach_audit_triggers()
LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.relname
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema()
          AND c.relkind IN ('r', 'p')
          AND NOT c.relispartition
          AND EXISTS (SELECT 1 FROM pg_attribute a
                      WHERE a.attrelid = c.oid AND a.attname = 'updated_at' AND NOT a.attisdropped)
          AND NOT EXISTS (SELECT 1 FROM pg_trigger t
                          WHERE t.tgrelid = c.oid AND t.tgname = 'trg_' || c.relname || '_audit')
    LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION trg_set_audit_columns()',
                       'trg_' || r.relname || '_audit', r.relname);
    END LOOP;
END $$;

-- Make a table append-only (blocks UPDATE, DELETE and TRUNCATE for every role
-- that does not own it; the owner role is never used by the application).
CREATE OR REPLACE PROCEDURE make_append_only(p_table text)
LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION trg_forbid_modification()',
                   'trg_' || p_table || '_append_only', p_table);
    EXECUTE format('CREATE TRIGGER %I BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION trg_forbid_modification()',
                   'trg_' || p_table || '_no_truncate', p_table);
END $$;

-- Monthly range partitions: <table>_pYYYYMM plus <table>_pdefault (rule group 8).
CREATE OR REPLACE PROCEDURE create_monthly_partitions(p_table text, p_from date, p_to date)
LANGUAGE plpgsql AS $$
DECLARE d date := date_trunc('month', p_from);
BEGIN
    WHILE d < p_to LOOP
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF %I FOR VALUES FROM (%L) TO (%L)',
                       p_table || '_p' || to_char(d, 'YYYYMM'), p_table, d, (d + interval '1 month')::date);
        d := (d + interval '1 month')::date;
    END LOOP;
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF %I DEFAULT', p_table || '_pdefault', p_table);
END $$;

-- -----------------------------------------------------------------------------
-- user_account (shell; owned by Administration, Phase 2)
-- Phase 2 adds credentials, roles, status, phone, locale, consent links.
-- -----------------------------------------------------------------------------
CREATE TABLE user_account (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    email           varchar(254) NOT NULL,
    is_system       boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    deleted_at      timestamptz,
    CONSTRAINT ck_user_account_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_user_account_email_format CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);
CREATE UNIQUE INDEX uq_user_account_email ON user_account (email) WHERE deleted_at IS NULL;

-- System actor (id 1) used by migrations, schedulers and seeding. Ids < 1000 are reserved.
INSERT INTO user_account (id, email, is_system, created_by, updated_by)
VALUES (1, 'system@talentra.internal', true, 1, 1);

-- -----------------------------------------------------------------------------
-- organisation (shell; owned by Organisation and account, Phase 2)
-- Phase 2 adds hierarchy, tax ids, verification, locations, recruiter mapping.
-- -----------------------------------------------------------------------------
CREATE TABLE organisation (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    legal_name      varchar(250) NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    deleted_at      timestamptz
);

COMMENT ON COLUMN user_account.email      IS 'class=Personal; login identity, lowercase';
COMMENT ON COLUMN user_account.deleted_at IS 'class=Internal; null=account not deleted (soft delete)';
COMMENT ON COLUMN organisation.legal_name IS 'class=Public';
COMMENT ON COLUMN organisation.deleted_at IS 'class=Internal; null=organisation not deleted (soft delete)';

CALL attach_audit_triggers();
