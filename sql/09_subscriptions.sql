-- -----------------------------------------------------------------------------
-- Wallet (credits) and its append-only ledger. One wallet per account; balance is
-- the running total of the ledger, cached on the wallet.
-- -----------------------------------------------------------------------------
CREATE TABLE wallet (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organisation_id bigint      NOT NULL REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    credit_balance  integer     NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_wallet_credit_balance CHECK (credit_balance >= 0)
);
CREATE UNIQUE INDEX uq_wallet_organisation_id ON wallet (organisation_id);

-- A correction is a new entry that references the original (rule group 10), never an update.
CREATE TABLE wallet_ledger_entry (
    id                              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    wallet_id                       bigint       NOT NULL REFERENCES wallet (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    wallet_entry_type_id            bigint       NOT NULL REFERENCES wallet_entry_type (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    credit_delta                    integer      NOT NULL,
    balance_after                   integer      NOT NULL,
    payment_order_id                bigint REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    refund_id                       bigint REFERENCES refund (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    reverses_wallet_ledger_entry_id bigint REFERENCES wallet_ledger_entry (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    note                            varchar(250),
    occurred_at                     timestamptz  NOT NULL DEFAULT now(),
    created_at                      timestamptz  NOT NULL DEFAULT now(),
    created_by                      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_wallet_ledger_entry_credit_delta CHECK (credit_delta <> 0),
    CONSTRAINT ck_wallet_ledger_entry_balance_after CHECK (balance_after >= 0),
    -- entry type decides the sign and the reference it must carry (SYSTEM ids, see the lookup)
    CONSTRAINT ck_wallet_ledger_entry_recharge CHECK ((wallet_entry_type_id = 1) = (payment_order_id IS NOT NULL)),
    CONSTRAINT ck_wallet_ledger_entry_refund CHECK ((wallet_entry_type_id = 3) = (refund_id IS NOT NULL)),
    CONSTRAINT ck_wallet_ledger_entry_reversal CHECK ((wallet_entry_type_id = 4) = (reverses_wallet_ledger_entry_id IS NOT NULL)),
    CONSTRAINT ck_wallet_ledger_entry_sign CHECK (CASE WHEN wallet_entry_type_id = 1 THEN credit_delta > 0
                                                       WHEN wallet_entry_type_id IN (2, 3, 6) THEN credit_delta < 0 ELSE true END)
);
CREATE INDEX idx_wallet_ledger_entry_wallet_id ON wallet_ledger_entry (wallet_id, occurred_at);
-- A recharge order credits the wallet once; a refund debits it once (1 : 0..1 each).
CREATE UNIQUE INDEX uq_wallet_ledger_entry_payment_order_id ON wallet_ledger_entry (payment_order_id) WHERE payment_order_id IS NOT NULL;
CREATE UNIQUE INDEX uq_wallet_ledger_entry_refund_id ON wallet_ledger_entry (refund_id) WHERE refund_id IS NOT NULL;
CREATE UNIQUE INDEX uq_wallet_ledger_entry_reverses ON wallet_ledger_entry (reverses_wallet_ledger_entry_id) WHERE reverses_wallet_ledger_entry_id IS NOT NULL;
CALL make_append_only('wallet_ledger_entry');

