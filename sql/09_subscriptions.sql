-- =============================================================================
-- Talentra :: 09_subscriptions.sql
-- Module: Subscriptions, wallet, payments and download history — individual, Phase 3, Member C
-- Plans and entitlements, subscriptions and their periods (renewals, cancellation),
-- payment orders and gateway events, invoices, refunds, the credit wallet and its
-- append-only ledger, and profile download history.
-- Payment gateway boundary (docket §6): stores order/transaction references, status
-- and amounts; never card or bank data. Built after Organisation (D12: the account
-- is the root organisation) and before Licences (a licence comes from a subscription).
-- =============================================================================
SET app.current_user_id = '1';

CALL create_lookup_table('billing_period',       'monthly, quarterly, half_yearly, annual');
CALL create_lookup_table('entitlement_type',     'job_posting, profile_download, outreach_message, featured_job');
CALL create_lookup_table('subscription_status',  'trial, active, past_due, cancelled, expired');
CALL create_lookup_table('payment_purpose',      'subscription, wallet_recharge');
CALL create_lookup_table('payment_order_status', 'created, pending, paid, failed, cancelled, refunded, partially_refunded');
CALL create_lookup_table('refund_status',        'requested, processing, completed, failed');
CALL create_lookup_table('wallet_entry_type',    'recharge, consumption, refund, reversal, adjustment, expiry');

CALL seed_lookups('billing_period', ARRAY['monthly|Monthly', 'quarterly|Quarterly', 'half_yearly|Half-yearly', 'annual|Annual']);
CALL seed_lookups('entitlement_type', ARRAY['job_posting|Job postings', 'profile_download|Profile downloads',
                                            'outreach_message|Outreach messages', 'featured_job|Featured jobs']);
CALL seed_lookups('subscription_status', ARRAY['trial|Trial', 'active|Active', 'past_due|Past due', 'cancelled|Cancelled', 'expired|Expired']);
CALL seed_lookups('payment_purpose', ARRAY['subscription|Subscription', 'wallet_recharge|Wallet recharge']);
CALL seed_lookups('payment_order_status', ARRAY['created|Created', 'pending|Pending', 'paid|Paid', 'failed|Failed', 'cancelled|Cancelled',
                                                'refunded|Refunded', 'partially_refunded|Partially refunded']);
CALL seed_lookups('refund_status', ARRAY['requested|Requested', 'processing|Processing', 'completed|Completed', 'failed|Failed']);
CALL seed_lookups('wallet_entry_type', ARRAY['recharge|Recharge', 'consumption|Consumption', 'refund|Refund', 'reversal|Reversal',
                                             'adjustment|Adjustment', 'expiry|Expiry']);

-- -----------------------------------------------------------------------------
-- Plans and entitlements. A plan states the licence limits it sells; the licence
-- copies them at purchase, so editing a plan never changes an existing licence.
-- -----------------------------------------------------------------------------
CREATE TABLE plan (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    code                 varchar(50)   NOT NULL,
    ui_label_key_id      bigint        NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    billing_period_id    bigint        NOT NULL REFERENCES billing_period (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    price_amount         numeric(14,2) NOT NULL,
    price_currency_id    bigint        NOT NULL REFERENCES currency (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    max_users            integer       NOT NULL,
    max_devices_per_user integer       NOT NULL,
    sort_order           integer       NOT NULL DEFAULT 0,
    is_active            boolean       NOT NULL DEFAULT true,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    created_by           bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    updated_by           bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_plan_code UNIQUE (code),
    CONSTRAINT ck_plan_code_format CHECK (code ~ '^[a-z0-9_]+$'),
    CONSTRAINT ck_plan_price_amount CHECK (price_amount >= 0),
    CONSTRAINT ck_plan_max_users CHECK (max_users > 0),
    CONSTRAINT ck_plan_max_devices_per_user CHECK (max_devices_per_user > 0)
);

CREATE TABLE plan_entitlement (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    plan_id               bigint      NOT NULL REFERENCES plan (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    entitlement_type_id   bigint      NOT NULL REFERENCES entitlement_type (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    quantity_per_period   integer,
    created_at            timestamptz NOT NULL DEFAULT now(),
    created_by            bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    updated_by            bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_plan_entitlement_plan_id_entitlement_type_id UNIQUE (plan_id, entitlement_type_id),
    CONSTRAINT ck_plan_entitlement_quantity_per_period CHECK (quantity_per_period > 0)
);

-- -----------------------------------------------------------------------------
-- Payments (gateway boundary)
-- -----------------------------------------------------------------------------
CREATE TABLE payment_order (
    id                        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organisation_id           bigint        NOT NULL REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    placed_by_user_account_id bigint        NOT NULL REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    payment_purpose_id        bigint        NOT NULL REFERENCES payment_purpose (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    order_amount              numeric(14,2) NOT NULL,
    order_currency_id         bigint        NOT NULL REFERENCES currency (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    credit_quantity           integer,
    payment_order_status_id   bigint        NOT NULL DEFAULT 1 REFERENCES payment_order_status (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    gateway_order_ref         varchar(100),
    paid_at                   timestamptz,
    created_at                timestamptz   NOT NULL DEFAULT now(),
    created_by                bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at                timestamptz   NOT NULL DEFAULT now(),
    updated_by                bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_payment_order_gateway_order_ref UNIQUE (gateway_order_ref),
    CONSTRAINT ck_payment_order_order_amount CHECK (order_amount > 0),
    -- a wallet recharge (purpose 2) states the credits it buys; a subscription order buys none
    CONSTRAINT ck_payment_order_credit_quantity CHECK (credit_quantity > 0 AND payment_purpose_id = 2
                                                       OR credit_quantity IS NULL AND payment_purpose_id <> 2)
);
CREATE INDEX idx_payment_order_organisation_id ON payment_order (organisation_id, created_at DESC);

-- Gateway callbacks as received: status history of an order, idempotent by the
-- gateway's event id (a redelivered webhook is rejected by the unique constraint).
CREATE TABLE payment_event (
    id                      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_order_id        bigint       NOT NULL REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    payment_order_status_id bigint       NOT NULL REFERENCES payment_order_status (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    gateway_event_ref       varchar(100) NOT NULL,
    gateway_payment_ref     varchar(100),
    occurred_at             timestamptz  NOT NULL,
    created_at              timestamptz  NOT NULL DEFAULT now(),
    created_by              bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_payment_event_gateway_event_ref UNIQUE (gateway_event_ref)
);
CREATE INDEX idx_payment_event_payment_order_id ON payment_event (payment_order_id, occurred_at);
CALL make_append_only('payment_event');

-- Invoices are immutable once issued; corrections are refunds (credit notes).
CREATE TABLE invoice (
    id                            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_order_id              bigint        NOT NULL REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    invoice_number                varchar(30)   NOT NULL,
    issued_at                     timestamptz   NOT NULL DEFAULT now(),
    billing_name                  varchar(250)  NOT NULL,
    billing_tax_identifier_masked varchar(30),
    subtotal_amount               numeric(14,2) NOT NULL,
    tax_amount                    numeric(14,2) NOT NULL,
    total_amount                  numeric(14,2) NOT NULL,
    invoice_currency_id           bigint        NOT NULL REFERENCES currency (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at                    timestamptz   NOT NULL DEFAULT now(),
    created_by                    bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_invoice_invoice_number UNIQUE (invoice_number),
    CONSTRAINT ck_invoice_amounts CHECK (subtotal_amount >= 0 AND tax_amount >= 0 AND total_amount = subtotal_amount + tax_amount)
);
CREATE UNIQUE INDEX uq_invoice_payment_order_id ON invoice (payment_order_id);
CALL make_append_only('invoice');

CREATE TABLE refund (
    id                 bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_order_id   bigint        NOT NULL REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    refund_amount      numeric(14,2) NOT NULL,
    refund_currency_id bigint        NOT NULL REFERENCES currency (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    refund_status_id   bigint        NOT NULL DEFAULT 1 REFERENCES refund_status (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    reason             varchar(500)  NOT NULL,
    gateway_refund_ref varchar(100),
    requested_at       timestamptz   NOT NULL DEFAULT now(),
    processed_at       timestamptz,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    created_by         bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    updated_by         bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_refund_gateway_refund_ref UNIQUE (gateway_refund_ref),
    CONSTRAINT ck_refund_refund_amount CHECK (refund_amount > 0),
    CONSTRAINT ck_refund_date_range CHECK (processed_at >= requested_at)
);
CREATE INDEX idx_refund_payment_order_id ON refund (payment_order_id);

-- -----------------------------------------------------------------------------
-- Subscriptions: one subscription per purchase of a plan; each billing cycle
-- (first term, every renewal) is a period. Cancellation stops renewal.
-- -----------------------------------------------------------------------------
CREATE TABLE subscription (
    id                     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organisation_id        bigint       NOT NULL REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    plan_id                bigint       NOT NULL REFERENCES plan (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    subscription_status_id bigint       NOT NULL REFERENCES subscription_status (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    is_auto_renew          boolean      NOT NULL DEFAULT true,
    started_at             timestamptz  NOT NULL DEFAULT now(),
    cancelled_at           timestamptz,
    cancellation_reason    varchar(500),
    created_at             timestamptz  NOT NULL DEFAULT now(),
    created_by             bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    updated_by             bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    -- target of licence's composite FK: a licence belongs to the subscribing organisation
    CONSTRAINT uq_subscription_id_organisation_id UNIQUE (id, organisation_id),
    CONSTRAINT ck_subscription_date_range CHECK (cancelled_at >= started_at),
    CONSTRAINT ck_subscription_cancellation CHECK (cancellation_reason IS NULL OR cancelled_at IS NOT NULL)
);
CREATE INDEX idx_subscription_organisation_id ON subscription (organisation_id);

CREATE TABLE subscription_period (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subscription_id  bigint      NOT NULL REFERENCES subscription (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    renewal_number   integer     NOT NULL DEFAULT 0,
    period_start_at  timestamptz NOT NULL,
    period_end_at    timestamptz NOT NULL,
    payment_order_id bigint REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_subscription_period_subscription_id_renewal_number UNIQUE (subscription_id, renewal_number),
    CONSTRAINT ck_subscription_period_renewal_number CHECK (renewal_number >= 0),
    CONSTRAINT ck_subscription_period_date_range CHECK (period_end_at > period_start_at)
);
-- An order pays for at most one period (1 : 0..1).
CREATE UNIQUE INDEX uq_subscription_period_payment_order_id ON subscription_period (payment_order_id) WHERE payment_order_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- Wallet (credits) and its append-only ledger. One wallet per account; balance is
-- the running total of the ledger, cached on the wallet.
-- -----------------------------------------------------------------------------
CREATE TABLE wallet (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organisation_id bigint      NOT NULL REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    credit_balance  integer     NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_wallet_credit_balance CHECK (credit_balance >= 0)
);
CREATE UNIQUE INDEX uq_wallet_organisation_id ON wallet (organisation_id);

-- A correction is a new entry that references the original (rule group 10), never an update.
CREATE TABLE wallet_ledger_entry (
    id                              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    wallet_id                       bigint       NOT NULL REFERENCES wallet (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    wallet_entry_type_id            bigint       NOT NULL REFERENCES wallet_entry_type (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    credit_delta                    integer      NOT NULL,
    balance_after                   integer      NOT NULL,
    payment_order_id                bigint REFERENCES payment_order (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    refund_id                       bigint REFERENCES refund (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    reverses_wallet_ledger_entry_id bigint REFERENCES wallet_ledger_entry (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    note                            varchar(250),
    occurred_at                     timestamptz  NOT NULL DEFAULT now(),
    created_at                      timestamptz  NOT NULL DEFAULT now(),
    created_by                      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_wallet_ledger_entry_credit_delta CHECK (credit_delta <> 0),
    CONSTRAINT ck_wallet_ledger_entry_balance_after CHECK (balance_after >= 0)
);
CREATE INDEX idx_wallet_ledger_entry_wallet_id ON wallet_ledger_entry (wallet_id, occurred_at);
-- A recharge order credits the wallet once; a refund debits it once (1 : 0..1 each).
CREATE UNIQUE INDEX uq_wallet_ledger_entry_payment_order_id ON wallet_ledger_entry (payment_order_id) WHERE payment_order_id IS NOT NULL;
CREATE UNIQUE INDEX uq_wallet_ledger_entry_refund_id ON wallet_ledger_entry (refund_id) WHERE refund_id IS NOT NULL;
CREATE UNIQUE INDEX uq_wallet_ledger_entry_reverses ON wallet_ledger_entry (reverses_wallet_ledger_entry_id) WHERE reverses_wallet_ledger_entry_id IS NOT NULL;
CALL make_append_only('wallet_ledger_entry');

-- -----------------------------------------------------------------------------
-- Profile download history: actor, subject, time and the credit deduction.
-- Append-only, monthly partitions.
-- -----------------------------------------------------------------------------
CREATE TABLE profile_download_event (
    id                          bigint GENERATED ALWAYS AS IDENTITY,
    candidate_profile_id        bigint      NOT NULL REFERENCES candidate_profile (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    downloader_user_account_id  bigint      NOT NULL REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    downloader_organisation_id  bigint REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    resume_version_id           bigint REFERENCES resume_version (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    wallet_ledger_entry_id      bigint REFERENCES wallet_ledger_entry (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    downloaded_at               timestamptz NOT NULL DEFAULT now(),
    created_at                  timestamptz NOT NULL DEFAULT now(),
    created_by                  bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT pk_profile_download_event PRIMARY KEY (id, downloaded_at)
) PARTITION BY RANGE (downloaded_at);
CREATE INDEX idx_profile_download_event_candidate_profile_id ON profile_download_event (candidate_profile_id, downloaded_at);
CREATE INDEX idx_profile_download_event_downloader_organisation_id ON profile_download_event (downloader_organisation_id, downloaded_at);
CALL create_monthly_partitions('profile_download_event', DATE '2025-01-01', DATE '2027-01-01');
CALL make_append_only('profile_download_event');

-- Phase 1 hand-off: a profile view that consumes credit points at its ledger entry.
ALTER TABLE profile_view_event
    ADD COLUMN wallet_ledger_entry_id bigint REFERENCES wallet_ledger_entry (id) ON UPDATE RESTRICT ON DELETE RESTRICT;

-- -----------------------------------------------------------------------------
-- Classification and nullability justification (rule groups 5, 6)
-- -----------------------------------------------------------------------------
COMMENT ON COLUMN plan.price_amount                    IS 'class=Public; price per billing period';
COMMENT ON COLUMN plan.max_users                       IS 'class=Public; users allowed per licence (> 0)';
COMMENT ON COLUMN plan.max_devices_per_user            IS 'class=Public; devices allowed per user (> 0)';
COMMENT ON COLUMN plan_entitlement.quantity_per_period IS 'class=Public; null=unlimited within the period';
COMMENT ON COLUMN payment_order.order_amount           IS 'class=Internal';
COMMENT ON COLUMN payment_order.credit_quantity        IS 'class=Internal; credits bought (price fixed at order time); null=subscription order';
COMMENT ON COLUMN payment_order.gateway_order_ref      IS 'class=Internal; idempotency key at the gateway; null=order not yet sent to the gateway';
COMMENT ON COLUMN payment_order.paid_at                IS 'class=Internal; null=not paid';
COMMENT ON COLUMN payment_event.gateway_event_ref      IS 'class=Internal; webhook id, idempotency key';
COMMENT ON COLUMN payment_event.gateway_payment_ref    IS 'class=Internal; gateway transaction id (no card or bank data); null=event before a transaction exists';
COMMENT ON COLUMN payment_event.occurred_at            IS 'class=Internal; time reported by the gateway';
COMMENT ON COLUMN invoice.invoice_number               IS 'class=Internal';
COMMENT ON COLUMN invoice.issued_at                    IS 'class=Internal';
COMMENT ON COLUMN invoice.billing_name                 IS 'class=Internal; legal name at issue time';
COMMENT ON COLUMN invoice.billing_tax_identifier_masked IS 'class=Internal; masked tax id printed on the invoice; null=buyer without a tax registration';
COMMENT ON COLUMN invoice.subtotal_amount              IS 'class=Internal';
COMMENT ON COLUMN invoice.tax_amount                   IS 'class=Internal';
COMMENT ON COLUMN invoice.total_amount                 IS 'class=Internal; = subtotal + tax (CHECK)';
COMMENT ON COLUMN refund.refund_amount                 IS 'class=Internal';
COMMENT ON COLUMN refund.reason                        IS 'class=Internal';
COMMENT ON COLUMN refund.gateway_refund_ref            IS 'class=Internal; null=not yet submitted to the gateway';
COMMENT ON COLUMN refund.requested_at                  IS 'class=Internal';
COMMENT ON COLUMN refund.processed_at                  IS 'class=Internal; null=not processed yet';
COMMENT ON COLUMN subscription.started_at              IS 'class=Internal';
COMMENT ON COLUMN subscription.cancelled_at            IS 'class=Internal; null=not cancelled';
COMMENT ON COLUMN subscription.cancellation_reason     IS 'class=Internal; null=not cancelled or no reason given';
COMMENT ON COLUMN subscription_period.renewal_number   IS 'class=Internal; 0 = first term';
COMMENT ON COLUMN subscription_period.period_start_at  IS 'class=Internal';
COMMENT ON COLUMN subscription_period.period_end_at    IS 'class=Internal';
COMMENT ON COLUMN subscription_period.payment_order_id IS 'class=Internal; null=trial or complimentary period';
COMMENT ON COLUMN wallet.credit_balance                IS 'class=Internal; running total of the ledger';
COMMENT ON COLUMN wallet_ledger_entry.credit_delta     IS 'class=Internal; + credit, - debit, never 0';
COMMENT ON COLUMN wallet_ledger_entry.balance_after    IS 'class=Internal';
COMMENT ON COLUMN wallet_ledger_entry.payment_order_id IS 'class=Internal; null=entry not funded by a payment (consumption, adjustment)';
COMMENT ON COLUMN wallet_ledger_entry.refund_id        IS 'class=Internal; null=entry not caused by a refund';
COMMENT ON COLUMN wallet_ledger_entry.reverses_wallet_ledger_entry_id IS 'class=Internal; null=not a correction of an earlier entry';
COMMENT ON COLUMN wallet_ledger_entry.note             IS 'class=Internal; null=no note';
COMMENT ON COLUMN wallet_ledger_entry.occurred_at      IS 'class=Internal';
COMMENT ON COLUMN profile_download_event.downloader_organisation_id IS 'class=Internal; null=freelance consultant without organisation';
COMMENT ON COLUMN profile_download_event.resume_version_id IS 'class=Internal; null=profile export without a resume file';
COMMENT ON COLUMN profile_download_event.wallet_ledger_entry_id IS 'class=Internal; null=download covered by a plan entitlement, no credit used';
COMMENT ON COLUMN profile_download_event.downloaded_at IS 'class=Internal; partition key';
COMMENT ON COLUMN profile_view_event.wallet_ledger_entry_id IS 'class=Internal; null=view consumed no credit';

CALL attach_audit_triggers();
RESET app.current_user_id;
