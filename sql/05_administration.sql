-- =============================================================================
-- Talentra :: 05_administration.sql   (Module: Administration — individual, Phase 2, Member A)
-- Users (extends the 00 shell), roles, permissions, role grants and the audit trail.
-- Credentials, consent records, identity sessions and blocking lists are listed by
-- the docket under the Phase 4 shared team items (B50); they are added there.
-- Lookups created here are reference data owned by Master data.
-- =============================================================================
SET app.current_user_id = '1';

CALL create_lookup_table('user_account_status', 'SYSTEM: 1=active; suspended, locked, deactivated');
CALL create_lookup_table('audit_action',        'sensitive actions recorded in audit_event');

CALL seed_lookups('user_account_status', ARRAY['active|Active', 'suspended|Suspended', 'locked|Locked', 'deactivated|Deactivated']);
CALL seed_lookups('audit_action', ARRAY[
    'create|Create', 'update|Update', 'delete|Delete', 'login|Login', 'login_failed|Login failed', 'logout|Logout',
    'role_grant|Role granted', 'role_revoke|Role revoked', 'block|Block', 'unblock|Unblock',
    'profile_view|Profile viewed', 'profile_download|Profile downloaded', 'data_export|Data exported',
    'verification_change|Verification status changed', 'erasure|Personal data erased']);

-- -----------------------------------------------------------------------------
-- user_account (extends the 00 shell)
-- -----------------------------------------------------------------------------
ALTER TABLE user_account
    ADD COLUMN user_account_status_id bigint NOT NULL DEFAULT 1 REFERENCES user_account_status (id) ON UPDATE RESTRICT ON DELETE RESTRICT;

CREATE VIEW v_user_account AS
    SELECT * FROM user_account WHERE deleted_at IS NULL;

-- -----------------------------------------------------------------------------
-- Roles and permissions. One row per actor in docket §3; ids 1..9 are fixed so
-- access rules can name them. Organisation-scoped roles take effect only through
-- an organisation_member row (Organisation module).
-- -----------------------------------------------------------------------------
CREATE TABLE role (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    code                   varchar(50) NOT NULL,
    ui_label_key_id        bigint      NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    is_organisation_scoped boolean     NOT NULL DEFAULT false,
    sort_order             integer     NOT NULL DEFAULT 0,
    is_active              boolean     NOT NULL DEFAULT true,
    created_at             timestamptz NOT NULL DEFAULT now(),
    created_by             bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    updated_by             bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_role_code UNIQUE (code),
    CONSTRAINT ck_role_code_format CHECK (code ~ '^[a-z0-9_]+$')
);

CREATE TABLE permission (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    code            varchar(100) NOT NULL,          -- <resource>.<action>, e.g. job_requirement.publish
    ui_label_key_id bigint       NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_permission_code UNIQUE (code),
    CONSTRAINT ck_permission_code_format CHECK (code ~ '^[a-z0-9_]+\.[a-z0-9_]+$')
);

CREATE TABLE role_permission (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    role_id       bigint      NOT NULL REFERENCES role (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    permission_id bigint      NOT NULL REFERENCES permission (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    created_at    timestamptz NOT NULL DEFAULT now(),
    created_by    bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    updated_by    bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_role_permission_role_id_permission_id UNIQUE (role_id, permission_id)
);
CREATE INDEX idx_role_permission_permission_id ON role_permission (permission_id);

-- Grants are never deleted: revocation sets revoked_at, so who held a role when is answerable.
CREATE TABLE user_account_role (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_account_id bigint      NOT NULL REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    role_id         bigint      NOT NULL REFERENCES role (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    granted_at      timestamptz NOT NULL DEFAULT now(),
    revoked_at      timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_user_account_role_date_range CHECK (revoked_at >= granted_at)
);
-- One live grant per user and role.
CREATE UNIQUE INDEX uq_user_account_role_user_account_id_role_id ON user_account_role (user_account_id, role_id) WHERE revoked_at IS NULL;
CREATE INDEX idx_user_account_role_role_id ON user_account_role (role_id);

-- -----------------------------------------------------------------------------
-- Audit trail (rule group 4: append-only). created_by is the actor. Monthly
-- partitions so retention drops whole months.
-- -----------------------------------------------------------------------------
CREATE TABLE audit_event (
    id               bigint GENERATED ALWAYS AS IDENTITY,
    audit_action_id  bigint      NOT NULL REFERENCES audit_action (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    target_table     varchar(63) NOT NULL,
    target_record_id bigint,
    organisation_id  bigint REFERENCES organisation (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    occurred_at      timestamptz NOT NULL DEFAULT now(),
    source_ip        inet,
    user_agent       varchar(500),
    detail           jsonb,
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT pk_audit_event PRIMARY KEY (id, occurred_at),
    CONSTRAINT ck_audit_event_target_table_format CHECK (target_table ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT ck_audit_event_detail_size CHECK (pg_column_size(detail) <= 8192)
) PARTITION BY RANGE (occurred_at);
CREATE INDEX idx_audit_event_target_table_target_record_id ON audit_event (target_table, target_record_id, occurred_at);
CREATE INDEX idx_audit_event_created_by ON audit_event (created_by, occurred_at);
CALL create_monthly_partitions('audit_event', DATE '2025-01-01', DATE '2027-01-01');
CALL make_append_only('audit_event');

-- -----------------------------------------------------------------------------
-- Reference rows: the nine actors of docket §3
-- -----------------------------------------------------------------------------
DO $$
DECLARE r record; k bigint; n int := 0;
BEGIN
    FOR r IN SELECT * FROM (VALUES
        ('super_admin','Super Admin',false), ('admin','Admin',false), ('account_admin','Account Admin',true),
        ('guest','Guest',false), ('candidate','Candidate',false), ('employer','Employer',true),
        ('recruiter','Recruiter',true), ('consultant','Consultant',false), ('placement_officer','Placement Officer (TPO)',false)
    ) AS v(code, label, scoped)
    LOOP
        n := n + 1;
        CALL seed_label('role.' || r.code, 'administration', k);
        CALL seed_translation('role.' || r.code, 'en', r.label);
        INSERT INTO role (id, code, ui_label_key_id, is_organisation_scoped, sort_order) VALUES (n, r.code, k, r.scoped, n * 10);
    END LOOP;
END $$;

-- -----------------------------------------------------------------------------
-- Classification and nullability justification (rule groups 5, 6)
-- -----------------------------------------------------------------------------
COMMENT ON COLUMN user_account_role.revoked_at   IS 'class=Internal; null=grant is live';
COMMENT ON COLUMN audit_event.target_table       IS 'class=Internal; table the action touched';
COMMENT ON COLUMN audit_event.target_record_id   IS 'class=Internal; null=action not on a single row (bulk export, failed login for unknown user)';
COMMENT ON COLUMN audit_event.organisation_id    IS 'class=Internal; null=action outside an organisation context (candidate, platform admin)';
COMMENT ON COLUMN audit_event.source_ip          IS 'class=Personal; null=server-side action (scheduled job)';
COMMENT ON COLUMN audit_event.user_agent         IS 'class=Personal; null=server-side action';
COMMENT ON COLUMN audit_event.detail             IS 'class=Personal; changed fields, never secrets; bounded 8 KB; null=action needs no detail';

COMMENT ON COLUMN user_account_role.granted_at   IS 'class=Internal; grant takes effect';
COMMENT ON COLUMN audit_event.occurred_at        IS 'class=Internal; UTC time of the action (partition key)';
CALL attach_audit_triggers();
RESET app.current_user_id;
