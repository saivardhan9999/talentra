CREATE TABLE ui_label_key (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    label_key       varchar(150) NOT NULL,
    module_code     varchar(50)  NOT NULL,
    description     varchar(500),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_ui_label_key_label_key UNIQUE (label_key),
    CONSTRAINT ck_ui_label_key_label_key_format CHECK (label_key ~ '^[a-z0-9_]+(\.[a-z0-9_]+)*$')
);

CREATE TABLE language (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    code            varchar(15)  NOT NULL,          -- BCP 47 tag: en, hi, ta, zh-Hans
    native_name     varchar(100) NOT NULL,
    ui_label_key_id bigint       NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    is_ui_supported boolean      NOT NULL DEFAULT false,
    is_default      boolean      NOT NULL DEFAULT false,
    sort_order      integer      NOT NULL DEFAULT 0,
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_language_code UNIQUE (code),
    CONSTRAINT ck_language_default_is_ui CHECK (NOT is_default OR is_ui_supported)
);
-- Exactly one default (fallback) UI language.
CREATE UNIQUE INDEX uq_language_is_default ON language (is_default) WHERE is_default;

CREATE TABLE ui_label_translation (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    ui_label_key_id bigint        NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    language_id     bigint        NOT NULL REFERENCES language (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    label_text      varchar(1000) NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    created_by      bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    updated_by      bigint        NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_ui_label_translation_key_language UNIQUE (ui_label_key_id, language_id),
    CONSTRAINT ck_ui_label_translation_label_text_not_blank CHECK (btrim(label_text) <> '')
);

-- Fallback rule: requested language -> default language. NULL means the key has
-- no default translation, which the seed validation report treats as a defect.
CREATE OR REPLACE FUNCTION fn_ui_label(p_ui_label_key_id bigint, p_language_id bigint)
RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT t.label_text
    FROM ui_label_translation t
    JOIN language l ON l.id = t.language_id
    WHERE t.ui_label_key_id = p_ui_label_key_id
      AND (t.language_id = p_language_id OR l.is_default)
    ORDER BY (t.language_id = p_language_id) DESC
    LIMIT 1
$$;

-- -----------------------------------------------------------------------------
-- Generic enumeration (lookup) tables — rule group 3 "Enumeration".
-- Every lookup has the same shape; ids < 1000 are reserved for system values
-- that CHECK constraints rely on (seeded with explicit ids, codes immutable).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE create_lookup_table(p_table text, p_comment text)
LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format($f$
        CREATE TABLE %1$I (
            id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
            code            varchar(50) NOT NULL,
            ui_label_key_id bigint      NOT NULL REFERENCES ui_label_key (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
            sort_order      integer     NOT NULL DEFAULT 0,
            is_active       boolean     NOT NULL DEFAULT true,
            created_at      timestamptz NOT NULL DEFAULT now(),
            created_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
            updated_at      timestamptz NOT NULL DEFAULT now(),
            updated_by      bigint      NOT NULL DEFAULT app_current_user_id() REFERENCES user_account (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
            CONSTRAINT %2$I UNIQUE (code),
            CONSTRAINT %3$I CHECK (code ~ '^[a-z0-9_]+$')
        )$f$, p_table, 'uq_' || p_table || '_code', 'ck_' || p_table || '_code_format');
    EXECUTE format('COMMENT ON TABLE %I IS %L', p_table, 'lookup; ' || p_comment);
    -- System rows (id < 1000) are referenced by CHECK constraints: their code may not change.
    EXECUTE format($f$
        CREATE TRIGGER %1$I BEFORE UPDATE OF code, id ON %2$I FOR EACH ROW
        WHEN (OLD.id < 1000 AND (NEW.code IS DISTINCT FROM OLD.code OR NEW.id <> OLD.id))
        EXECUTE FUNCTION trg_forbid_modification()$f$, 'trg_' || p_table || '_system_code', p_table);
END $$;

